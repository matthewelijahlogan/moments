create extension if not exists pgcrypto;

create table if not exists public.moments (
  id uuid primary key default gen_random_uuid(),
  client_id text not null check (char_length(client_id) between 1 and 80),
  username text not null check (char_length(username) between 1 and 40),
  media_type text not null check (media_type in ('image', 'video')),
  storage_path text not null unique,
  score numeric(4, 1) not null check (score between 0 and 100),
  tier text not null,
  title text not null,
  summary text not null,
  dimensions jsonb not null default '{}'::jsonb,
  signals jsonb not null default '{}'::jsonb,
  explanation jsonb not null default '[]'::jsonb,
  clip_duration_seconds numeric(4, 1),
  published boolean not null default true,
  created_at timestamptz not null default now()
);

create index if not exists moments_public_leaderboard_idx
  on public.moments (score desc, created_at asc)
  where published = true;

create index if not exists moments_client_created_idx
  on public.moments (client_id, created_at desc);

alter table public.moments enable row level security;

comment on table public.moments is
  'Private service-owned archive metadata. Public clients read leaderboard data through the Render API.';
comment on column public.moments.client_id is
  'Opaque installation identifier generated by the mobile app; not an authentication credential.';
comment on column public.moments.storage_path is
  'Path inside the private moments-media Storage bucket.';

insert into storage.buckets (
  id,
  name,
  public,
  file_size_limit,
  allowed_mime_types
)
values (
  'moments-media',
  'moments-media',
  false,
  67108864,
  array[
    'image/jpeg',
    'image/png',
    'image/webp',
    'video/mp4',
    'video/quicktime'
  ]
)
on conflict (id) do update
set
  public = excluded.public,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

-- No anon/authenticated policies are intentionally created for either table.
-- The Render backend uses the service-role key; raw media remains private.
